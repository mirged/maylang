#!/usr/bin/env python3
"""Generate compiled editor docs and the readable reference from one catalog.

Catalog entries marked with `"source"` are functions defined in the standard
library; their text comes from the `///` comment on the definition.
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "docs/reference"))
import docstrings  # noqa: E402
import generate as reference  # noqa: E402


def render(entry):
    # Same layout as a /// comment rendered by the language server.
    return docstrings.markdown(dict(
        summary=entry["summary"], details=[entry["notes"]] if entry.get("notes") else [],
        params=[(p["name"], p["description"]) for p in entry.get("parameters", [])],
        returns=entry.get("returns", ""), faults=entry.get("faults", ""), example=entry["example"]))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog = reference.catalog()
    entries = {}
    chapters = ["# Maylang editor reference\n\n"
                "Generated from `reference.json` and, for functions defined in the "
                "standard library, their `///` comments; edit those and run "
                "`python3 docs/generate.py` from `tools/maylsp`. "
                "These descriptions also appear in hover, completion, and signature help. "
                "Signatures describe the public API; dynamic values may have several types.\n"]
    for group, values in catalog.items():
        chapters.append("\n## " + group + "\n")
        for name, entry in values.items():
            assert name not in entries, name
            assert entry["summary"] and entry["example"] and entry["signature"], name
            prose = render(entry)
            entries[name] = {"signature": entry["signature"], "docs": prose,
                             "params": [p["name"] for p in entry.get("parameters", [])],
                             "parameterDocs": {p["name"]: p["description"] for p in entry.get("parameters", [])}}
            chapters.append(f"\n### `{name}`\n\n```may\n{entry['signature']}\n```\n\n{prose}\n")
    source = "// Generated by docs/generate.py from docs/reference.json and stdlib doc comments.\nlet LS_REFERENCE: Any = "
    source += json.dumps(entries, ensure_ascii=False, indent=4) + ";\n"
    outputs = {HERE.parent / "src/docs.may": source, HERE / "REFERENCE.md": "".join(chapters)}
    for path, contents in outputs.items():
        if args.check:
            assert path.read_text() == contents, f"Regenerate {path}"
        else:
            path.write_text(contents)
    print(f"{'Checked' if args.check else 'Generated'} {len(entries)} documentation entries")


if __name__ == "__main__":
    main()
