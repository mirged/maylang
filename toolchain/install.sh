#!/bin/sh
# Install a downloaded release or select an already extracted bundle. No Python.
set -eu
fail() { echo "maylang-install: $*" >&2; exit 1; }
if [ "$#" -lt 1 ] || [ "$#" -gt 2 ]; then
    echo 'Usage: sh toolchain/install.sh ARCHIVE_OR_BUNDLE [INSTALL_ROOT]' >&2
    exit 2
fi
case "$(uname -s):$(uname -m)" in
    Linux:x86_64) ;;
    *) fail 'Current releases require Linux x86-64. On Windows, use WSL 2; native macOS releases are not available.' ;;
esac
input=$1
root=${2:-"$HOME/.local/share/maylang"}
mkdir -p "$root"
root=$(cd "$root" && pwd -P)
staging=$(mktemp -d "$root/.install-XXXXXX")
trap 'rm -rf "$staging"' EXIT HUP INT TERM
if [ -d "$input" ]; then
    bundle=$(cd "$input" && pwd -P)
else
    [ -f "$input" ] || fail "No archive or bundle at $input"
    [ -f "$input.sha256" ] || fail "Missing checksum: $input.sha256"
    expected=$(awk 'NR == 1 { print $1 }' "$input.sha256")
    [ "${#expected}" -eq 64 ] || fail 'Invalid archive checksum'
    actual=$(sha256sum "$input" | cut -d ' ' -f 1)
    [ "$actual" = "$expected" ] || fail 'Archive checksum mismatch'
    # Only extract the relative paths produced by package.py.
    tar -tzf "$input" > "$staging/entries"
    if ! awk '/^\// || /(^|\/)\.\.(\/|$)/ { bad=1 } END { exit bad }' "$staging/entries"; then
        fail 'Archive contains unsafe paths'
    fi
    tar -xzf "$input" -C "$staging" --no-same-owner
    set -- "$staging"/maylang-*-x86_64-linux
    [ "$#" -eq 1 ] && [ -d "$1" ] || fail 'Expected one Linux x86-64 bundle'
    bundle=$1
fi
for file in VERSION bin/mayc bin/may bin/mayfmt bin/maypkg bin/maylsp \
    bin/runtime.may bin/native.may bin/prelude.may bin/runtime/core.may stdlib/prelude.may; do
    [ -f "$bundle/$file" ] || fail "Incomplete bundle: missing $file"
done
version=$(cat "$bundle/VERSION")
printf '%s\n' "$version" | LC_ALL=C grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+(-[A-Za-z0-9.-]+)?$' || fail 'Invalid VERSION'
if [ -e "$root/current" ] && [ ! -L "$root/current" ]; then
    fail "$root/current exists and is not a symlink"
fi
case "$bundle" in
    "$staging"/*)
        destination="$root/maylang-$version-x86_64-linux"
        [ ! -e "$destination" ] || fail "Already installed: $destination; select this directory to reuse it"
        mv "$bundle" "$destination"
        bundle=$destination
        ;;
esac
for tool in mayc may mayfmt maypkg maylsp; do chmod +x "$bundle/bin/$tool"; done
# Quote the root for shell startup files, including spaces and apostrophes.
quoted_root=$(printf '%s' "$root" | sed "s/'/'\\\\''/g")
cat > "$staging/env.sh" <<EOF
# Generated by Maylang install.sh; source from a POSIX shell, Bash or Zsh.
export MAYLANG_STDLIB='$quoted_root/current/stdlib'
case ":\$PATH:" in
    *":\$MAYLANG_STDLIB/../bin:"*) ;;
    *) export PATH="\$MAYLANG_STDLIB/../bin:\$PATH" ;;
esac
EOF
ln -s "$bundle" "$staging/current"
mv "$staging/env.sh" "$root/env.sh"
mv -Tf "$staging/current" "$root/current"
echo "Installed Maylang $version"
printf "Refresh your shell: . '%s/env.sh'\n" "$quoted_root"
echo 'Add that same command to ~/.profile (or ~/.bashrc / ~/.zshrc) to enable future shells.'
